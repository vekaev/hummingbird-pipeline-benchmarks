P(`\n${paired.filter((p) => Math.abs(p.gd - p.td) <= FLOOR_D).length} of ${paired.length} clips fall inside the floor on LSE-D; `);
P(`${paired.filter((p) => Math.abs(p.gc - p.tc) <= 0.288).length} of ${paired.length} on LSE-C.\n`);

