#!/usr/bin/env node
/**
 * Writes results/reporting.md: the change ledger and the configuration table the brief
 * asked for.
 *
 * The ledger's facts live in results/raw/changes.json rather than in this script, and its
 * per-stage numbers are recomputed from results/raw/ here, so a change's stated effect and
 * the samples behind it cannot drift. A change whose effect is not yet measured renders as
 * "not measured" — the schema has no field for an estimate.
 *
 * Usage: node analysis/reporting.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mean, stdev, cv, fmt } from './stats.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const raw = (n) => JSON.parse(readFileSync(join(root, 'results/raw', `${n}.json`), 'utf8'));
const ledger = raw('changes');

const out = [];
const P = (s) => out.push(s);

P('# The work, and the configurations it was measured on\n');
P('Generated by `analysis/reporting.mjs`. The ledger below is committed data; every');
P('per-stage number in the configuration table is recomputed from `results/raw/`.\n');

// ---------------------------------------------------------------- the ledger
P('## Changes made\n');
const unmeasured = ledger.changes.filter((c) => c.effect !== 'measured');
const nWord = ['none', 'one', 'two', 'three', 'four'][unmeasured.length] ?? String(unmeasured.length);
P('In the order they were made. A change is only credited with an effect when a');
P(`measurement exists for it; the ${nWord} marked "not measured" ${unmeasured.length === 1 ? 'is' : 'are'} implemented and`);
P(`instrumented but ${unmeasured.length === 1 ? 'has' : 'have'} no number yet, and the reason is given.\n`);
P('| # | Change | What it does | Effect |');
P('|---:|---|---|---|');
for (const c of ledger.changes) {
  const eff = c.effect === 'measured' ? c.detail : `**not measured** — ${c.detail}`;
  P(`| ${c.n} | ${c.change} | ${c.what} | ${eff} |`);
}
P('');

// ---------------------------------------------------------------- the brief's table
P('## Per-stage timing by configuration\n');
P('The table the brief asked for: per-stage timing across several runs with hardware and');
P('video parameters noted, one row per configuration.\n');
P('Hardware is **measured** only for the A/B arms, where the runner writes the GPU model,');
P('driver and torch build into every log header. For the production configurations the');
P('container never prints its GPU, so hardware there is the deployment configuration and is');
P('labelled as such — it is not an observation.\n');

const STAGES = ['crop_face', 'detect_landmarks', 'parse_face', 'track_face', 'run_animator',
  'create_driving_geo_and_mask', 'predict_liveportait', 'reshape_liveportrait', 'render_rgb', 'paste_back_video'];
const LABEL = {
  crop_face: 'Crop', detect_landmarks: 'Landmarks', parse_face: 'Parsing', track_face: 'Tracking',
  run_animator: 'Animator', create_driving_geo_and_mask: 'Geometry', predict_liveportait: 'Warp',
  reshape_liveportrait: 'Reshape', render_rgb: 'Render', paste_back_video: 'Paste-back',
};
const pipelineOf = (r) => Object.values(r.stages).reduce((a, b) => a + b, 0);

P(`| Configuration | n | ${STAGES.map((s) => LABEL[s]).join(' | ')} | Pipeline |`);
P(`|---|---:|${STAGES.map(() => '---:').join('|')}|---:|`);
for (const c of ledger.configurations) {
  let runs;
  try { runs = raw(c.dataset); } catch { continue; }
  // A run without parsed stage timings cannot contribute to a stage mean and must not
  // be counted in n either, or the row would claim more evidence than it has. The
  // drift-control pass (arm0c) is wall-clock only and lands here.
  runs = runs.filter((r) => r.stages && Object.keys(r.stages).length);
  if (!runs.length) continue;
  const cells = STAGES.map((s) => {
    const v = runs.filter((r) => s in r.stages).map((r) => r.stages[s]);
    return v.length ? fmt(mean(v), 1) : '—';
  });
  P(`| ${c.label} | ${runs.length} | ${cells.join(' | ')} | ${fmt(mean(runs.map(pipelineOf)), 1)} |`);
}
P('');
P('All values are seconds, mean across the runs in that configuration. Rates and money');
P('appear only in the cost tables, where the assumed rate is printed with them.\n');

// ---------------------------------------------------------------- protocol key
P('## Configuration key\n');
P('Hardware and video parameters for each row of the table above. Hardware is an');
P('observation only where marked measured; elsewhere it is the deployment configuration,');
P('because the production container never prints the GPU it ran on.\n');
P('| Configuration | Hardware | Video parameters | Deployment | Protocol |');
P('|---|---|---|---|---|');
for (const c of ledger.configurations) {
  const hw = c.hardwareMeasured ? `**${c.hardware}**` : `${c.hardware} *(config, not measured)*`;
  P(`| ${c.label} | ${hw} | ${c.video} | ${c.deployment} | ${c.protocol} |`);
}
P('');

// ---------------------------------------------------------------- spread, restated here
P('## Measurement precision by configuration\n');
P('Whether a configuration can resolve the effect being tested. The A/B arms were run on a');
P('dedicated machine precisely because the production cohorts cannot: their clip-to-clip');
P('spread is larger than the effects under test.\n');
P('| Configuration | n | mean pipeline (s) | stdev (s) | CV | can resolve a 1% effect |');
P('|---|---:|---:|---:|---:|---|');
for (const c of ledger.configurations) {
  let runs;
  try { runs = raw(c.dataset); } catch { continue; }
  if (runs.length < 2) continue;
  const v = c.dataset === 'arms'
    ? runs.filter((r) => r.arm === 'arm0' && r.wall_s).map((r) => r.wall_s)
    : runs.filter((r) => r.stages && Object.keys(r.stages).length).map(pipelineOf);
  if (v.length < 2) continue;
  const c_ = cv(v);
  P(`| ${c.label} | ${v.length} | ${fmt(mean(v))} | ${fmt(stdev(v))} | ${fmt(c_, 3)} | ${c_ < 0.02 ? 'yes, paired' : 'no'} |`);
}
P('');

writeFileSync(join(root, 'results/reporting.md'), `${out.join('\n')}\n`);
console.log(`wrote results/reporting.md (${out.length} lines)`);
